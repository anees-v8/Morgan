from pydantic import BaseModel, Field
from typing import Optional, List, Dict, Any

class GenerateVideoRequest(BaseModel):
    url: str = Field(..., description="Target website URL (e.g. stripe.com)")
    style: str = Field("cinematic_saas", description="Video style: cinematic_saas, punchy_launch, minimal_portfolio")
    voice: Optional[str] = Field("en-US-ChristopherNeural", description="Voiceover identifier")
    include_watermark: bool = Field(True, description="Whether to include 'Generated by WebReel'")

class JobStatusResponse(BaseModel):
    job_id: str
    status: str  # pending, processing, completed, failed
    progress_percent: int
    current_stage: str
    url: str
    brand: Optional[Dict[str, Any]] = None
    video_url: Optional[str] = None
    download_url: Optional[str] = None
    scenes_count: Optional[int] = None
    duration_seconds: Optional[float] = None
    scenes: Optional[List[Dict[str, Any]]] = None
    error: Optional[str] = None
