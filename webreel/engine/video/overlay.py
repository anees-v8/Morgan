from PIL import Image, ImageDraw, ImageFont
from pathlib import Path
from typing import Tuple, Dict, Any, Optional

class VideoOverlay:
    def __init__(self, width: int = 1920, height: int = 1080):
        self.width = width
        self.height = height

    def create_lower_third(
        self,
        category: str,
        title: str,
        output_path: Path,
        brand_color: Tuple[int, int, int] = (0, 240, 255)
    ) -> Path:
        """
        Creates a glassmorphic lower-third PNG overlay with an accent bar.
        Position: 40px from left, 60px from bottom.
        """
        output_path.parent.mkdir(parents=True, exist_ok=True)
        img = Image.new("RGBA", (self.width, self.height), (0, 0, 0, 0))
        draw = ImageDraw.Draw(img)

        # Lower-third box parameters
        box_x = 40
        box_y = self.height - 130
        box_w = 460
        box_h = 70
        radius = 8

        # Draw semi-transparent dark card background
        draw.rounded_rectangle(
            [(box_x, box_y), (box_x + box_w, box_y + box_h)],
            radius=radius,
            fill=(10, 15, 25, 210),
            outline=(255, 255, 255, 30),
            width=1
        )

        # Draw left accent color bar
        draw.rounded_rectangle(
            [(box_x, box_y + 4), (box_x + 4, box_y + box_h - 4)],
            radius=2,
            fill=(*brand_color, 255)
        )

        # Try to load a clean font or fallback to default
        try:
            font_cat = ImageFont.truetype("arial.ttf", 11)
            font_title = ImageFont.truetype("arialbd.ttf", 18)
        except Exception:
            font_cat = ImageFont.load_default()
            font_title = ImageFont.load_default()

        # Text rendering
        draw.text((box_x + 18, box_y + 12), category.upper(), fill=(148, 163, 184, 255), font=font_cat)
        draw.text((box_x + 18, box_y + 32), title[:38], fill=(255, 255, 255, 255), font=font_title)

        img.save(str(output_path), "PNG")
        return output_path

    def create_watermark(self, output_path: Path) -> Path:
        """
        Creates the subtle "Generated by WebReel" bottom-right watermark.
        """
        output_path.parent.mkdir(parents=True, exist_ok=True)
        img = Image.new("RGBA", (self.width, self.height), (0, 0, 0, 0))
        draw = ImageDraw.Draw(img)

        try:
            font = ImageFont.truetype("arialbd.ttf", 14)
        except Exception:
            font = ImageFont.load_default()

        badge_w, badge_h = 200, 36
        bx = self.width - badge_w - 30
        by = self.height - badge_h - 30

        draw.rounded_rectangle(
            [(bx, by), (bx + badge_w, by + badge_h)],
            radius=6,
            fill=(8, 11, 18, 180),
            outline=(255, 255, 255, 20),
            width=1
        )
        draw.text((bx + 16, by + 10), "⚡ Generated by WebReel", fill=(255, 255, 255, 230), font=font)

        img.save(str(output_path), "PNG")
        return output_path

    def create_outro_card(self, brand: Dict[str, str], output_path: Path) -> Path:
        """
        Creates the cinematic branded outro frame.
        """
        output_path.parent.mkdir(parents=True, exist_ok=True)
        img = Image.new("RGBA", (self.width, self.height), (7, 9, 14, 255))
        draw = ImageDraw.Draw(img)

        name = brand.get("company_name", "WebReel")
        domain = brand.get("clean_domain", "webreel.in")
        tagline = brand.get("tagline", "Experience the Future.")

        try:
            font_title = ImageFont.truetype("arialbd.ttf", 52)
            font_tag = ImageFont.truetype("arial.ttf", 22)
            font_url = ImageFont.truetype("arialbd.ttf", 26)
        except Exception:
            font_title = ImageFont.load_default()
            font_tag = ImageFont.load_default()
            font_url = ImageFont.load_default()

        # Center typography
        draw.text((self.width // 2, self.height // 2 - 80), name, fill=(255, 255, 255), anchor="mm", font=font_title)
        draw.text((self.width // 2, self.height // 2 - 10), tagline, fill=(148, 163, 184), anchor="mm", font=font_tag)
        
        # Pill button for domain
        bw, bh = 340, 56
        bx, by = self.width // 2 - bw // 2, self.height // 2 + 50
        draw.rounded_rectangle([(bx, by), (bx + bw, by + bh)], radius=28, fill=(0, 240, 255, 255))
        draw.text((self.width // 2, by + bh // 2), f"Visit {domain} →", fill=(7, 9, 14), anchor="mm", font=font_url)

        img.save(str(output_path), "PNG")
        return output_path
