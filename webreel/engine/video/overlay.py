from PIL import Image, ImageDraw, ImageFont
from pathlib import Path
from typing import Tuple, Dict, Any, Optional

from .stage import font as _font, wrap_lines

class VideoOverlay:
    def __init__(self, width: int = 1920, height: int = 1080):
        self.width = width
        self.height = height

    def create_lower_third(
        self,
        category: str,
        title: str,
        output_path: Path,
        brand_color: Tuple[int, int, int] = (0, 240, 255)
    ) -> Path:
        """
        Creates a glassmorphic lower-third PNG overlay with an accent bar.
        Position: 40px from left, 60px from bottom.
        """
        output_path.parent.mkdir(parents=True, exist_ok=True)
        img = Image.new("RGBA", (self.width, self.height), (0, 0, 0, 0))
        draw = ImageDraw.Draw(img)

        # Lower-third box parameters
        box_x = 40
        box_y = self.height - 130
        box_w = 460
        box_h = 70
        radius = 8

        # Draw semi-transparent dark card background
        draw.rounded_rectangle(
            [(box_x, box_y), (box_x + box_w, box_y + box_h)],
            radius=radius,
            fill=(10, 15, 25, 210),
            outline=(255, 255, 255, 30),
            width=1
        )

        # Draw left accent color bar
        draw.rounded_rectangle(
            [(box_x, box_y + 4), (box_x + 4, box_y + box_h - 4)],
            radius=2,
            fill=(*brand_color, 255)
        )

        # Try to load a clean font or fallback to default
        try:
            font_cat = ImageFont.truetype("arial.ttf", 11)
            font_title = ImageFont.truetype("arialbd.ttf", 18)
        except Exception:
            font_cat = ImageFont.load_default()
            font_title = ImageFont.load_default()

        # Text rendering
        draw.text((box_x + 18, box_y + 12), category.upper(), fill=(148, 163, 184, 255), font=font_cat)
        draw.text((box_x + 18, box_y + 32), title[:38], fill=(255, 255, 255, 255), font=font_title)

        img.save(str(output_path), "PNG")
        return output_path

    def create_watermark(self, output_path: Path) -> Path:
        """
        Creates the subtle "Generated by WebReel" bottom-right watermark.
        """
        output_path.parent.mkdir(parents=True, exist_ok=True)
        ss = 3
        badge_w, badge_h = 200, 36
        bx = self.width - badge_w - 30
        by = self.height - badge_h - 30

        # Badge drawn supersampled so its rounded corners and the bolt are cleanly anti-aliased
        # (and the bolt is a vector shape: the old emoji glyph rendered as a tofu box).
        badge = Image.new("RGBA", (badge_w * ss, badge_h * ss), (0, 0, 0, 0))
        d = ImageDraw.Draw(badge)
        d.rounded_rectangle([0, 0, badge_w * ss - 1, badge_h * ss - 1], radius=8 * ss,
                            fill=(8, 11, 18, 190), outline=(255, 255, 255, 28), width=ss)
        bolt = [(10.0, 0.0), (3.0, 11.0), (8.0, 11.0), (6.0, 20.0), (15.0, 8.0), (9.5, 8.0), (12.0, 0.0)]
        ox, oy = 14, (badge_h - 20) / 2.0
        d.polygon([((x + ox) * ss, (y + oy) * ss) for x, y in bolt], fill=(255, 214, 10, 255))
        badge = badge.resize((badge_w, badge_h), Image.Resampling.LANCZOS)
        ImageDraw.Draw(badge).text((38, badge_h / 2.0), "Generated by WebReel", fill=(255, 255, 255, 235),
                                   font=_font("semibold", 13), anchor="lm")

        img = Image.new("RGBA", (self.width, self.height), (0, 0, 0, 0))
        img.paste(badge, (bx, by), badge)
        img.save(str(output_path), "PNG")
        return output_path

    def create_outro_card(self, brand: Dict[str, str], output_path: Path) -> Path:
        """
        Creates the cinematic branded outro frame.
        The "Visit <domain>" pill stays centred at (width/2, height/2 + 78): that is the point the
        on-screen pointer travels to and presses.
        """
        import numpy as np

        output_path.parent.mkdir(parents=True, exist_ok=True)
        W, H = self.width, self.height
        name = brand.get("company_name", "WebReel")
        domain = brand.get("clean_domain", "webreel.in")
        tagline = brand.get("tagline", "Experience the Future.")

        # Dark studio base with a soft cyan bloom behind the call-to-action (float, then dithered)
        ys, xs = np.mgrid[0:H // 4, 0:W // 4].astype(np.float32)
        cx, cy = W / 8.0, (H / 2.0 + 78) / 4.0
        glow = np.exp(-(((xs - cx) ** 2) / (2 * 150.0 ** 2) + ((ys - cy) ** 2) / (2 * 95.0 ** 2)))[:, :, None]
        base = np.array((7.0, 9.0, 14.0), np.float32)[None, None, :]
        img_f = base + glow * np.array((0.0, 38.0, 44.0), np.float32)[None, None, :]
        img_f = np.array(Image.fromarray(np.clip(img_f, 0, 255).astype(np.uint8)).resize((W, H), Image.Resampling.BICUBIC), np.float32)
        img_f += (np.random.default_rng(3).random((H, W, 1), dtype=np.float32) - 0.5) * 2.0   # dither vs banding
        img = Image.fromarray(np.clip(img_f, 0, 255).astype(np.uint8), "RGB").convert("RGBA")
        draw = ImageDraw.Draw(img)

        f_title = _font("bold", 66)
        f_tag = _font("regular", 25)
        f_url = _font("bold", 26)

        draw.text((W // 2, H // 2 - 100), name, fill=(255, 255, 255), anchor="mm", font=f_title)
        lines = wrap_lines(draw, tagline, f_tag, 1020, 2)
        ty = H // 2 - 34
        for ln in lines:
            draw.text((W // 2, ty), ln, fill=(148, 163, 184), anchor="mm", font=f_tag)
            ty += 36

        # Pill button for domain (centre fixed at y = H/2 + 78)
        label = f"Visit {domain}  →"
        bh = 56
        bw = int(max(340, draw.textlength(label, font=f_url) + 72))
        bx, by = W // 2 - bw // 2, H // 2 + 50
        ss = 3
        pill = Image.new("RGBA", (bw * ss, bh * ss), (0, 0, 0, 0))
        ImageDraw.Draw(pill).rounded_rectangle([0, 0, bw * ss - 1, bh * ss - 1], radius=bh * ss // 2, fill=(0, 240, 255, 255))
        pill = pill.resize((bw, bh), Image.Resampling.LANCZOS)
        img.paste(pill, (bx, by), pill)
        draw.text((W // 2, by + bh // 2), label, fill=(7, 9, 14), anchor="mm", font=f_url)

        img.convert("RGB").save(str(output_path), "PNG")
        return output_path
